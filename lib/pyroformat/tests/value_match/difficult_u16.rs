#[derive(Layout, Writer, Reader, Debug, PartialEq)]
#[pyro(Word = u16)]
struct PNullabilityListOptionU32 {
    a: Vec<Option<u32>>,
}

#[test]
fn value_match_nullability_list_option_u32_20() {
    let data = PNullabilityListOptionU32 {
        a: (0..20u32)
            .map(|i| if i % 3 == 0 { None } else { Some(i) })
            .collect(),
    };
    assert_roundtrip(
        &data,
        &NULLABILITY_LIST_OPTION_U32_20,
        &NULLABILITY_LIST_OPTION_U32_20_INODES,
    );
}

