use pyroformat::{Layout, Reader, Writer};

// ---------------------------------------------------------------------------
// Deep nesting: depth 4, 5 (primitive_nesting.rs caps out at 3)
// ---------------------------------------------------------------------------
//
// Plain numeric `Vec<Vec<...<u32>>>` nesting (no structs involved) is not
// capped the way struct-of-struct nesting is — verified empirically by
// building each depth's struct and round-tripping it against the source
// file's own golden `DEPTH_N_NESTED_U32`/`_INODES` consts, both writer and
// both reader surfaces (`assert_roundtrip`), before writing this file.

#[derive(Layout, Writer, Reader, Debug, PartialEq)]
#[pyro(Word = u16)]
struct PDepth4NestedU32 {
    a: Vec<Vec<Vec<Vec<u32>>>>,
}

#[derive(Layout, Writer, Reader, Debug, PartialEq)]
#[pyro(Word = u16)]
struct PDepth5NestedU32 {
    a: Vec<Vec<Vec<Vec<Vec<u32>>>>>,
}

#[test]
fn value_match_nesting_depth_4() {
    let data = PDepth4NestedU32 {
        a: vec![vec![vec![vec![11, 22]]]],
    };
    assert_roundtrip(&data, &DEPTH_4_NESTED_U32, &DEPTH_4_NESTED_U32_INODES);
}

#[test]
fn value_match_nesting_depth_5() {
    let data = PDepth5NestedU32 {
        a: vec![vec![vec![vec![vec![11, 22]]]]],
    };
    assert_roundtrip(&data, &DEPTH_5_NESTED_U32, &DEPTH_5_NESTED_U32_INODES);
}

