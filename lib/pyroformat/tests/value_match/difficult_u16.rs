// ---------------------------------------------------------------------------
// Extreme string / bytes lengths
// ---------------------------------------------------------------------------

#[derive(Layout, Writer, Reader, Debug, PartialEq)]
#[pyro(Word = u16)]
struct PStrExtreme {
    a: String,
}

#[derive(Layout, Writer, Reader, Debug, PartialEq)]
#[pyro(Word = u16)]
struct PBytesExtreme {
    a: Vec<u8>,
}

const STR_EXTREME_LEN: usize = 50_000;
const BYTES_EXTREME_LEN: usize = 50_000;

#[test]
fn value_match_str_extreme_length() {
    let data = PStrExtreme {
        a: "q".repeat(STR_EXTREME_LEN),
    };
    assert_roundtrip(&data, &STR_EXTREME, &STR_EXTREME_INODES);
}

#[test]
fn value_match_bytes_extreme_length() {
    let data = PBytesExtreme {
        a: (0..BYTES_EXTREME_LEN).map(|j| (j % 256) as u8).collect(),
    };
    assert_roundtrip(&data, &BYTES_EXTREME, &BYTES_EXTREME_INODES);
}

