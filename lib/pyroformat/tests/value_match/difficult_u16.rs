//! Struct-vs-value match for `src/wire/tests/difficult_u16.rs` — the torture
//! suite: deep nesting beyond depth 3, large cardinalities (a 1000-element
//! list, a 100-field group), extreme string/bytes lengths, and multi-byte
//! validity bitmasks. See `tests/value_match/primitive_u16.rs`'s module doc for
//! the shared rationale.

use pyroformat::wire::tests::difficult_u16::*;

