use anyhow::{Context, Result};
use rustpython_parser::ast;
use std::path::Path;
use std::fs;
use std::io::{self, Write};

/// Parses a Python file and generates Rust capability interfaces from @rust_interface decorated classes
pub async fn py2rs(python_file: &Path, output: Option<&Path>) -> Result<()> {
    // 1. Read the Python source file
    let content = fs::read_to_string(python_file)
        .with_context(|| format!("Failed to read python file: {}", python_file.display()))?;

    // 2. Parse into an Abstract Syntax Tree (AST)
    let program = rustpython_parser::parse_program(&content, &python_file.to_string_lossy())
        .map_err(|e| anyhow::anyhow!("Python syntax error: {}", e))?;

    // 3. Generate Rust code
    let rust_output = generate_rust_from_python(&program)?;

    // 4. Write output
    if let Some(output_path) = output {
        fs::write(output_path, &rust_output)
            .with_context(|| format!("Failed to write output to: {}", output_path.display()))?;
        println!("Generated Rust code written to: {}", output_path.display());
    } else {
        // Write to stdout
        io::stdout().write_all(rust_output.as_bytes())?;
    }

    Ok(())
}

/// Generates Rust code from Python AST
fn generate_rust_from_python(program: &[ast::Stmt]) -> Result<String> {
    let mut rust_output = String::from("// Auto-generated by pyroduct py2rs\nuse pyo3::prelude::*;\n\n");

    // First pass: collect all dataclasses
    let mut dataclasses = Vec::new();
    for stmt in program {
        if let ast::Stmt::ClassDef(class_def) = stmt {
            // Check for dataclass decorator
            let is_dataclass = class_def.decorator_list.iter().any(|dec| {
                matches!(dec, ast::Expr::Name(name) if name.id.as_str() == "dataclass")
            });

            if is_dataclass {
                dataclasses.push(class_def);
            }
        }
    }

    // Generate data structures
    for class_def in &dataclasses {
        let struct_def = transpile_dataclass_to_struct(class_def)?;
        rust_output.push_str(&struct_def);
        rust_output.push('\n');
    }

    // Second pass: generate interfaces
    for stmt in program {
        if let ast::Stmt::ClassDef(class_def) = stmt {
            // Check for the rust_interface decorator
            let is_interface = class_def.decorator_list.iter().any(|dec| {
                matches!(dec, ast::Expr::Name(name) if name.id.as_str() == "rust_interface")
            });

            if is_interface {
                let capability_def = transpile_class_to_capability(class_def)?;
                rust_output.push_str(&capability_def);
                rust_output.push('\n');
            }
        }
    }

    Ok(rust_output)
}

/// Converts a Python dataclass to a Rust struct with PyO3 derives
fn transpile_dataclass_to_struct(class_def: &ast::StmtClassDef) -> Result<String> {
    let class_name = &class_def.name;
    let mut fields = Vec::new();

    for item in &class_def.body {
        if let ast::Stmt::AnnAssign(ann_assign) = item {
            if let ast::Expr::Name(name) = &*ann_assign.target {
                let field_name = &name.id;
                let field_type = map_type(&ann_assign.annotation);
                fields.push(format!("    pub {}: {},", field_name, field_type));
            }
        }
    }

    Ok(format!(
        r#"#[derive(Clone, Debug, FromPyObject, ToPyObject)]
pub struct {} {{
{}
}}
"#,
        class_name,
        fields.join("\n")
    ))
}

/// Converts a Python @rust_interface class to a Rust capability
fn transpile_class_to_capability(class_def: &ast::StmtClassDef) -> Result<String> {
    let class_name = &class_def.name;
    let mut methods = Vec::new();

    for item in &class_def.body {
        if let ast::Stmt::FunctionDef(func) = item {
            if func.name.as_str().starts_with('_') { continue; } // Skip private/__init__

            // Map Arguments (skip self)
            let args: Vec<String> = func.args.args.iter()
                .filter(|arg| arg.def.arg.as_str() != "self")
                .map(|arg| {
                    let py_type = if let Some(ann) = &arg.def.annotation {
                        map_type(ann)
                    } else {
                        "PyObject".to_string()
                    };
                    format!("{}: {}", arg.def.arg, py_type)
                })
                .collect();

            // Map Return Type
            let ret_type = if let Some(ret) = &func.returns {
                map_type(ret)
            } else {
                "PyObject".to_string()
            };

            // Generate method signature
            methods.push(format!(
                "    fn {}(&self, {}) -> Result<{}, String> {{\n        todo!()\n    }}",
                func.name, args.join(", "), ret_type
            ));
        }
    }

    // Generate the full capability
    let pascal_name = format!("{}Server", class_name);
    let client_name = format!("{}Client", class_name);

    Ok(format!(
        r#"#[pyroduct::config]
pub struct {}Config {{
    // Add configuration fields here
}}

#[pyroduct::magma]
pub struct {} {{
    // Add client state here
}}

pub struct {} {{
    // Python module will be loaded here
}}

#[pyroduct::capability]
impl {} {{
    type Config = {}Config;
    type Client = {};
    type Error = String;

    fn new(_config: Option<{}Config>) -> Self {{
        // Load Python module and create instance
        Self {{ }}
    }}

    fn reset(&mut self) {{
        // Reset Python state
    }}

    fn register(&self, _client: &{}) -> Result<(), String> {{
        // Register client with Python
        Ok(())
    }}

    // Generated methods
{}
}}
"#,
        class_name, client_name, pascal_name, pascal_name,
        class_name, client_name, class_name, client_name,
        methods.join("\n")
    ))
}

/// Maps Python AST types to Rust types
fn map_type(expr: &Box<ast::Expr>) -> String {
    match expr.as_ref() {
        ast::Expr::Name(name) => match name.id.as_str() {
            "str" => "String".to_string(),
            "int" => "i64".to_string(),
            "bool" => "bool".to_string(),
            "float" => "f64".to_string(),
            "None" => "()".to_string(),
            _ => {
                // Check if it's a dataclass we know about
                // For now, assume it's a custom type
                name.id.to_string()
            }
        },
        ast::Expr::Subscript(sub) => {
            if let ast::Expr::Name(name) = &*sub.value {
                if name.id.as_str() == "List" {
                    if let ast::Expr::Name(elem_type) = &*sub.slice {
                        match elem_type.id.as_str() {
                            "str" => "Vec<String>".to_string(),
                            "int" => "Vec<i64>".to_string(),
                            "bool" => "Vec<bool>".to_string(),
                            "float" => "Vec<f64>".to_string(),
                            _ => format!("Vec<{}>", elem_type.id),
                        }
                    } else {
                        "Vec<PyObject>".to_string()
                    }
                } else {
                    "PyObject".to_string()
                }
            } else {
                "PyObject".to_string()
            }
        },
        _ => "PyObject".to_string(),
    }
}